#!/usr/bin/env python3
"""Generate src/core/combination_report_data.cpp from the text exports captured in the original CYPE 3D.

Inputs (docs/research/original_export, UTF-16 LE with BOM, CRLF, 120 columns):
  s1.txt    pencil 1 report, snow altitude <= 1000 m
  s1hi.txt  pencil 1 report, snow altitude  > 1000 m
  s2.txt    pencil 2 report (cold-formed steel + timber), snow altitude <= 1000 m

Only the coefficient tables are extracted; the fixed prose of the report lives in combination_report.cpp and is
checked against these same files by the golden tests. Run from the repository root:
  python tools/gen_combination_data.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "docs" / "research" / "original_export"
OUT = ROOT / "src" / "core" / "combination_report_data.cpp"

TOP_BORDER = re.compile(r"^ \|-{117}\| $")


def read(name):
    with open(SRC / name, encoding="utf-16", newline="") as f:
        return f.read().split("\r\n")


def parse_cell(text):
    text = text.strip()
    return None if text == "-" else float(text)


def group_by_section(lines):
    """Split the tables of a report into one list per report section (titles start at column 0)."""
    sections, current = [], None
    i = 0
    while i < len(lines):
        if TOP_BORDER.match(lines[i]):
            if current is None:
                current = []
                sections.append(current)
            title = lines[i + 1].strip().strip("|").strip()
            j = i + 2
            while "Favorable" not in lines[j]:
                j += 1
            j += 2
            rows = []
            while not lines[j].startswith(" |---"):
                cells = lines[j].strip().strip("|").split("|")
                if cells[0].strip():
                    rows.append((cells[0].strip(), [parse_cell(c) for c in cells[1:5]]))
                j += 1
            current.append((title, rows))
            i = j
        elif lines[i] and not lines[i].startswith(" ") and current:
            current = None
        i += 1
    return sections


def cell_src(v):
    return "{false, 0.0}" if v is None else "{true, %.3f}" % v


def row_src(label, cells, hi):
    parts = ["{\"%s\", {%s}" % (label, ", ".join(cell_src(c) for c in cells))]
    if hi is None or hi == cells:
        parts.append(", false, {}}")
    else:
        parts.append(", true, {%s}}" % ", ".join(cell_src(c) for c in hi))
    return "".join(parts)


def emit_set(name, tables_lo, tables_hi):
    out = ["const RawTable k%s[] = {" % name]
    for (title, rows), (title_hi, rows_hi) in zip(tables_lo, tables_hi):
        assert title == title_hi and [r[0] for r in rows] == [r[0] for r in rows_hi]
        out.append("    {\"%s\", {" % title)
        for (label, cells), (_, cells_hi) in zip(rows, rows_hi):
            out.append("        " + row_src(label, cells, cells_hi) + ",")
        out.append("    }},")
    out.append("};")
    return out


def main():
    s1, s1hi, s2 = read("s1.txt"), read("s1hi.txt"), read("s2.txt")
    sec1, sec1hi = group_by_section(s1), group_by_section(s1hi)
    sec2 = group_by_section(s2)
    assert len(sec1) == 5 and len(sec1hi) == 5 and len(sec2) == 1, (len(sec1), len(sec1hi), len(sec2))
    # s1 sections: 0 concrete, 1 aluminium, 2 ground A1 (identical coefficient tables), 3 ground A2, 4 service.
    assert sec1[0] == sec1[1] == sec1[2] and sec1hi[0] == sec1hi[1] == sec1hi[2]
    sets = [
        ("ConcreteAluminiumGroundA1", sec1[0], sec1hi[0]),
        ("GroundA2", sec1[3], sec1hi[3]),
        ("ServiceQuasiPermanent", sec1[4], sec1hi[4]),
        # The pencil 2 report was captured only for altitude <= 1000 m (ticket TK-017): reuse it for both.
        ("ColdFormedTimber", sec2[0], sec2[0]),
    ]
    out = [
        "// GENERATED by tools/gen_combination_data.py from docs/research/original_export/*.txt - do not edit.",
        "#include \"core/combination_report_data.h\"",
        "",
        "namespace cc::core::detail {",
        "",
    ]
    for name, lo, hi in sets:
        out += emit_set(name, lo, hi)
        out.append("")
    out.append("const RawTableSet kTableSets[] = {")
    for name, lo, _ in sets:
        out.append("    {k%s, %d}," % (name, len(lo)))
    out.append("};")
    out.append("const int kTableSetCount = %d;" % len(sets))
    out.append("")
    out.append("}  // namespace cc::core::detail")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("wrote", OUT.relative_to(ROOT), "-", [(n, len(lo)) for n, lo, _ in sets])


if __name__ == "__main__":
    sys.exit(main())
