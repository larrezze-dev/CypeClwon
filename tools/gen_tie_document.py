"""Generates src/core/tie_document_data.inc: the Spanish texts #64092-#64120 of the document "CALCULO DE TIRANTES EN CYPE 3D" of the
original (ed3dlib.dll, ed3ayuda.c FUN_180077490), read from docs/research/ui/data/strings_merged_latin.tsv (column es)."""
import csv, pathlib, sys

root = pathlib.Path(__file__).resolve().parent.parent
rows = {}
with open(root / 'docs/research/ui/data/strings_merged_latin.tsv', encoding='utf-8', newline='') as f:
    for row in csv.reader(f, delimiter='\t', quoting=csv.QUOTE_NONE):
        if row and row[0].isdigit() and 64092 <= int(row[0]) <= 64120:
            rows[int(row[0])] = row[3]
if len(rows) != 29:
    sys.exit('expected 29 strings, found %d' % len(rows))
out = ['// Generated by tools/gen_tie_document.py from strings_merged_latin.tsv (ids 64092-64120). Do not edit.']
for i in sorted(rows):
    text = rows[i]
    assert ')"' not in text
    out.append('{%d, R"(%s)"},' % (i, text))
(root / 'src/core/tie_document_data.inc').write_text('\n'.join(out) + '\n', encoding='utf-8')
print('written', len(rows))
