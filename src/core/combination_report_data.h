#pragma once
#include <vector>

namespace cc::core::detail {

/// Raw coefficient as captured: "-" in the original is `present == false`.
struct RawCell {
    bool present = false;
    double value = 0.0;
};

/// One row of a coefficient table. `hi` replaces `lo` when the snow altitude is above 1000 m (only snow rows differ).
struct RawRow {
    const char* label;
    RawCell lo[4];  ///< favourable, unfavourable, principal (psi_p), accompanying (psi_a)
    bool hasHi;
    RawCell hi[4];
};

struct RawTable {
    const char* title;
    std::vector<RawRow> rows;
};

struct RawTableSet {
    const RawTable* tables;
    int count;
};

/// Indexed by cc::core::TableSetId.
extern const RawTableSet kTableSets[];
extern const int kTableSetCount;

// Generated by tools/gen_combination_data.py (combination_report_data.cpp).
extern const RawTable kConcreteAluminiumGroundA1[];
extern const RawTable kGroundA2[];
extern const RawTable kServiceQuasiPermanent[];
extern const RawTable kColdFormedTimber[];

}  // namespace cc::core::detail
