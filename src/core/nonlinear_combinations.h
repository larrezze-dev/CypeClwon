#pragma once
#include <array>
#include <cstddef>
#include <map>
#include <string>
#include <vector>

namespace cc::core {

struct Project;
struct LoadCaseSet;

/// Non-linear combinations (T-P8-06, core part). Behaviour source: docs/research/solver_diafragmas_ligaduras_apoyos.md sections 5, 10.1 and 12.5,
/// docs/research/resultados_calculo.md and the screenshots s_5.png, s_9.png, s_10.png (Cálculo > «Combinaciones no lineales», button NL).
///
/// The original enables the non-linear analysis as soon as the work has a spring to the ground with a «Sentido» other than «Ambos». Each
/// non-linear combination is then solved on its own (no superposition, fem::solveNonlinear) and its results are listed as «[n] reference»
/// ("[1] PP", "[2] 1.35·PP") under «Combinaciones no lineales» in the result panels [V]. The dialog has the columns Referencia | Actúa |
/// Escalones de carga (default 10) and the panels «Tipos de combinación» and «Factores de combinación» (Hipótesis | coefficient) [V s_10.png].
/// The load steps are kept as data only: the clone solves the unilateral springs exactly by an active set, whose final state does not depend on
/// the load path (measured: [2] 1.35·PP = 1.35 x [1] PP with the spring released, section 10.1).

/// Check boxes of «Generar combinaciones para las distintas situaciones de proyecto» (blue arrow of the dialog), in their order [V s_9.png].
enum class NonlinearCombinationKind { Strength, Cracking, LongTermCracking, Displacements, FoundationEquilibrium, GroundStresses };
inline constexpr int kNonlinearCombinationKindCount = 6;
using NonlinearKinds = std::array<bool, kNonlinearCombinationKindCount>;

/// «Resistencia», «Fisuración», «Fisuración bajo cargas de larga duración», «Desplazamientos», «Equilibrio de los elementos de cimentación»,
/// «Tensiones en el terreno» [V s_9.png].
std::string nonlinearCombinationKindName(NonlinearCombinationKind kind);

/// Default of the column «Escalones de carga» [V s_10.png].
inline constexpr int kDefaultLoadSteps = 10;

struct NonlinearCombination {
    std::string reference;                ///< column «Referencia»: the formula name of the original ("PP", "1.35·PP")
    bool acts = true;                     ///< column «Actúa»
    int loadSteps = kDefaultLoadSteps;    ///< column «Escalones de carga» (data only, see above)
    std::map<int, double> factors;        ///< «Factores de combinación»: load case id -> coefficient (zeros not stored)
    NonlinearKinds kinds{};               ///< the kinds it was generated for («Tipos de combinación»)
    bool operator==(const NonlinearCombination&) const = default;
};

struct NonlinearCombinations {
    std::vector<NonlinearCombination> items;
    NonlinearKinds generateKinds{};  ///< last choice of the generation dialog, used by «Actualizar ... tras el análisis lineal»
    /// «Actualizar las combinaciones no lineales tras el análisis lineal» of the calculation dialog: shown (checked) once the work has
    /// non-linear combinations [V section 12.5].
    bool updateAfterLinear = true;
    bool operator==(const NonlinearCombinations&) const = default;
};

/// Name of the item in the result combos and in the solver messages: "[n] reference", n = position in the list from 1 [V "[1] PP"].
std::string nonlinearCombinationLabel(const NonlinearCombinations& set, std::size_t index);

struct NonlinearGeneration {
    std::vector<NonlinearCombination> items;
    std::string error;                  ///< error of the combination generator (empty = ok)
    std::vector<NonlinearCombinationKind> unsupported;  ///< kinds asked for but not generated by the clone (see the .cpp)
};

/// Generation of «Generar combinaciones para las distintas situaciones de proyecto»: the combinations of the chosen kinds, deduplicated by
/// coefficient vector ACROSS kinds and kept in the order of generation (kind order, then the order of core::generateCombinations). Measured: a
/// work with only the self weight, Resistencia + Desplazamientos -> "PP", "1.35·PP" [V s_10.png]. See the .cpp for the mapping of every kind.
NonlinearGeneration generateNonlinearCombinations(const Project& project, const NonlinearKinds& kinds);

/// «No es posible realizar el cálculo ya que hay combinaciones no lineales en las que intervienen hipótesis que no actúan. Elimine las
/// combinaciones afectadas o borre las hipótesis que no actúan.» (#381789, ed3dlib.dll).
std::string nonlinearCaseNotActingMessage();
/// Empty when every acting non-linear combination uses only load cases that act; otherwise nonlinearCaseNotActingMessage(). A factor for a load
/// case that no longer exists is ignored.
std::string checkNonlinearCombinations(const NonlinearCombinations& set, const LoadCaseSet& cases);

/// «Se van a borrar las combinaciones no lineales y de pandeo en las que interviene la hipótesis.» (#380751): the warning of the deletion.
std::string nonlinearCombinationsOfCaseWillBeDeletedMessage();
/// True when some non-linear combination has a non-zero factor for the load case (the GUI then shows #380751 before deleting it).
bool nonlinearCombinationsUseCase(const NonlinearCombinations& set, int loadCaseId);
/// Deleting a load case deletes the non-linear combinations in which it takes part (#380751).
void applyNonlinearCombinationsCaseDeleted(NonlinearCombinations& set, int loadCaseId);

/// «No se ha realizado el análisis de tensión/deformación no lineal» (#378613, ed3dlib.dll; the final report of s_5.png shows the same text,
/// without spaces around the slash): the work has unilateral springs but no non-linear combination.
std::string nonlinearAnalysisNotDoneMessage();
/// «Se han generado '%lu' combinaciones.» (#378563, combsanl).
std::string generatedCombinationsMessage(std::size_t count);

}  // namespace cc::core
